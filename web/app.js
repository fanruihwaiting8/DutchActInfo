/* Dutch Weekend Activities - static front-end.
   Reads window.ACTIVITY_DATA (generated by tools/fetch_events.py). */
(function (global) {
  'use strict';

  var PAGE_SIZE = 40;
  var MONTHS = ['January', 'February', 'March', 'April', 'May', 'June',
    'July', 'August', 'September', 'October', 'November', 'December'];
  var DAYS = ['Sunday', 'Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday'];
  var CATEGORY_LABEL = { festival: 'FESTIVAL', concert: 'CONCERT', comedy: 'COMEDY', other: 'EVENT' };

  /* ---------------------------------------------------------------- utils */

  function pad(value) { return value < 10 ? '0' + value : String(value); }

  function parseISO(iso) {
    var parts = String(iso || '').split('-');
    if (parts.length !== 3) { return null; }
    var date = new Date(Date.UTC(+parts[0], +parts[1] - 1, +parts[2]));
    return isNaN(date.getTime()) ? null : date;
  }

  function weekdayOf(iso) {
    var date= parseISO(iso);
    return date ? date.getUTCDay() : -1;
  }

  function formatDay(iso) {
    var date = parseISO(iso);
    if (!date) { return iso; }
    return DAYS[date.getUTCDay()] + ' ' + date.getUTCDate() + ' ' + MONTHS[date.getUTCMonth()];
  }

  function formatRange(startISO, endISO) {
    var a = parseISO(startISO);
    var b = parseISO(endISO);
    if (!a) { return startISO; }
    if (!b || startISO === endISO) {
      return a.getUTCDate() + ' ' + MONTHS[a.getUTCMonth()];
    }
    if (a.getUTCMonth() === b.getUTCMonth()) {
      return a.getUTCDate() + '-' + b.getUTCDate() + ' ' + MONTHS[a.getUTCMonth()];
    }
    return a.getUTCDate() + ' ' + MONTHS[a.getUTCMonth()] + ' - ' + b.getUTCDate() + ' ' + MONTHS[b.getUTCMonth()];
  }

  function todayISO(now) {
    var date = now || new Date();
    return date.getFullYear() + '-' + pad(date.getMonth() + 1) + '-' + pad(date.getDate());
  }

  /* Expand every event into one entry per weekend date it covers. */
  function expand(events) {
    var out = [];
    (events || []).forEach(function (event) {
      var dates = event.dates && event.dates.length ? event.dates : [event.start];
      dates.forEach(function (date) {
        out.push({ date: date, event: event });
      });
    });
    out.sort(function (a, b) {
      if (a.date !== b.date) { return a.date < b.date ? -1 : 1; }
      var ca = a.event.city || '';
      var cb = b.event.city || '';
      if (ca !== cb) { return ca < cb ? -1 : 1; }
      return (a.event.title || '') < (b.event.title || '') ? -1 : 1;
    });
    return out;
  }

  /* The next weekend block: the upcoming Fri-Sun that still has entries. */
  function nextWeekendDates(entries, today) {
    var future = entries.filter(function (item) { return item.date >= today; });
    if (!future.length) { return []; }
    var first = future[0].date;
    var anchor = parseISO(first);
    var limit = new Date(anchor.getTime());
    limit.setUTCDate(limit.getUTCDate() + (anchor.getUTCDay() === 5 ? 2 : anchor.getUTCDay() === 6 ? 1 : 0));
    var limitISO = limit.getUTCFullYear() + '-' + pad(limit.getUTCMonth() + 1) + '-' + pad(limit.getUTCDate());
    return [first, limitISO];
  }

  function monthKey(iso) { return String(iso).slice(0, 7); }

  function matchesFilters(item, state, context) {
    var event = item.event;
    if (state.cat !== 'all' && event.category !== state.cat) { return false; }
    if (state.province !== 'all' && event.province !== state.province) { return false; }
    if (state.city !== 'all' && event.city !== state.city) { return false; }
    if (state.day !== 'all' && weekdayOf(item.date) !== +state.day) { return false; }

    if (state.when === 'next') {
      if (!context.nextRange.length) { return false; }
      if (item.date < context.nextRange[0] || item.date > context.nextRange[1]) { return false; }
    } else if (state.when === 'month') {
      if (monthKey(item.date) !== context.thisMonth) { return false; }
    } else if (state.when === 'nextmonth') {
      if (monthKey(item.date) !== context.nextMonth) { return false; }
    } else if (item.date < context.today) {
      return false;
    }

    if (state.q) {
      var haystack = [event.title, event.city, event.venue, event.province,
        (event.performers || []).join(' ')].join(' ').toLowerCase();
      var terms = state.q.toLowerCase().split(/\s+/).filter(Boolean);
      for (var i = 0; i < terms.length; i += 1) {
        if (haystack.indexOf(terms[i]) < 0) { return false; }
      }
    }
    return true;
  }

  function filterEntries(entries, state, context) {
    return entries.filter(function (item) { return matchesFilters(item, state, context); });
  }

  function groupByDate(items) {
    var groups = [];
    var index = {};
    items.forEach(function (item) {
      if (!index[item.date]) {
        index[item.date] = { date: item.date, items: [] };
        groups.push(index[item.date]);
      }
      index[item.date].items.push(item);
    });
    return groups;
  }

  var api = {
    parseISO: parseISO,
    formatDay: formatDay,
    formatRange: formatRange,
    expand: expand,
    nextWeekendDates: nextWeekendDates,
    filterEntries: filterEntries,
    groupByDate: groupByDate,
    todayISO: todayISO
  };

  if (typeof module === 'object' && module.exports) { module.exports = api; }
  global.ActivityCore = api;

  if (typeof document === 'undefined') { return; }

  /* ------------------------------------------------------------- rendering */

  var data = global.ACTIVITY_DATA || { events: [], sources: [], provinces: [] };
  var entries = expand(data.events);
  var state = { q: '', when: 'all', cat: 'all', province: 'all', city: 'all', day: 'all', shown: PAGE_SIZE };
  var context = {
    today: todayISO(),
    nextRange: [],
    thisMonth: '',
    nextMonth: ''
  };
  context.nextRange = nextWeekendDates(entries, context.today);
  context.thisMonth = monthKey(data.window ? data.window.from : context.today);
  context.nextMonth = monthKey(data.window ? data.window.to : context.today);

  var el = {};

  function cacheElements() {
    el = {
      results: document.getElementById('results'),
      count: document.getElementById('count'),
      empty: document.getElementById('empty'),
      q: document.getElementById('q'),
      province: document.getElementById('province'),
      city: document.getElementById('city'),
      day: document.getElementById('day'),
      reset: document.getElementById('reset'),
      updated: document.getElementById('updated'),
      sources: document.getElementById('sources'),
      windowLabel: document.getElementById('window-label'),
      about: document.getElementById('about'),
      aboutBtn: document.getElementById('about-btn'),
      aboutSources: document.getElementById('about-sources')
    };
  }

  function fillSelect(select, values, allLabel) {
    select.innerHTML = '';
    var option = document.createElement('option');
    option.value = 'all';
    option.textContent = allLabel;
    select.appendChild(option);
    values.forEach(function (value) {
      var item = document.createElement('option');
      item.value = value;
      item.textContent = value;
      select.appendChild(item);
    });
  }

  function provinceList() {
    var seen = {};
    (data.events || []).forEach(function (event) { if (event.province) { seen[event.province] = 1; } });
    return Object.keys(seen).sort();
  }

  function cityList(province) {
    var seen = {};
    (data.events || []).forEach(function (event) {
      if (province !== 'all' && event.province !== province) { return; }
      if (event.city) { seen[event.city] = 1; }
    });
    return Object.keys(seen).sort();
  }

  function card(item) {
    var event = item.event;
    var node = document.createElement('a');
    node.className = 'card';
    node.href = event.url || '#';
    node.target = '_blank';
    node.rel = 'noopener noreferrer';

    var top = document.createElement('div');
    top.className = 'card-top';
    var badge = document.createElement('span');
    badge.className = 'badge ' + (event.category || 'other');
    badge.textContent = CATEGORY_LABEL[event.category] || CATEGORY_LABEL.other;
    var title = document.createElement('h3');
    title.textContent = event.title;
    top.appendChild(badge);
    top.appendChild(title);
    node.appendChild(top);

    var meta = document.createElement('p');
    meta.className = 'meta';
    var bits = [];
    if (event.time) { bits.push({ text: event.time, strong: false }); }
    bits.push({ text: event.city, strong: true });
    if (event.venue) { bits.push({ text: event.venue, strong: false }); }
    if (event.province) { bits.push({ text: event.province, strong: false }); }
    bits.forEach(function (bit, index) {
      if (index > 0) {
        var dot = document.createElement('span');
        dot.className = 'dot';
        dot.textContent = '\u00b7';
        meta.appendChild(dot);
      }
      var piece = document.createElement(bit.strong ? 'strong' : 'span');
      piece.textContent = bit.text;
      meta.appendChild(piece);
    });
    node.appendChild(meta);

    if ((event.performers || []).length) {
      var lineup = document.createElement('p');
      lineup.className = 'lineup';
      lineup.textContent = 'Line-up: ' + event.performers.slice(0, 6).join(', ');
      node.appendChild(lineup);
    } else if (event.description) {
      var desc = document.createElement('p');
      desc.className = 'desc';
      desc.textContent = event.description.slice(0, 140);
      node.appendChild(desc);
    }

    if (event.start !== event.end) {
      var span = document.createElement('span');
      span.className = 'multi';
      span.textContent = 'Runs ' + formatRange(event.start, event.end);
      node.appendChild(span);
    }
    return node;
  }

  function fillSources(target, sources) {
    if (!target) { return; }
    while (target.firstChild) { target.removeChild(target.firstChild); }
    if (!sources.length) { return; }
    target.appendChild(document.createTextNode('Sources: '));
    sources.forEach(function (source, index) {
      if (index > 0) { target.appendChild(document.createTextNode(' \u00b7 ')); }
      var link = document.createElement('a');
      link.href = source.site;
      link.target = '_blank';
      link.rel = 'noopener noreferrer';
      link.textContent = source.name;
      target.appendChild(link);
      target.appendChild(document.createTextNode(' (' + (source.count || 0) + ')'));
    });
  }

  function render() {
    var matched = filterEntries(entries, state, context);
    var visible = matched.slice(0, state.shown);
    var groups = groupByDate(visible);

    el.results.innerHTML = '';
    groups.forEach(function (group) {
      var wrap = document.createElement('div');
      wrap.className = 'day-group';
      var head = document.createElement('div');
      head.className = 'day-head';
      var heading = document.createElement('h2');
      heading.textContent = formatDay(group.date);
      var n = document.createElement('span');
      n.className = 'n';
      n.textContent = group.items.length + (group.items.length === 1 ? ' activity' : ' activities');
      head.appendChild(heading);
      head.appendChild(n);
      wrap.appendChild(head);
      group.items.forEach(function (item) { wrap.appendChild(card(item)); });
      el.results.appendChild(wrap);
    });

    if (matched.length > visible.length) {
      var more = document.createElement('button');
      more.type = 'button';
      more.className = 'more';
      more.textContent = 'Show more (' + (matched.length - visible.length) + ' left)';
      more.addEventListener('click', function () {
        state.shown += PAGE_SIZE * 2;
        render();
      });
      el.results.appendChild(more);
    }

    el.empty.hidden = matched.length > 0;
    el.count.textContent = matched.length
      ? matched.length + ' activities on ' + groupByDate(matched).length + ' weekend days'
      : '';
  }

  function bindChips(rowId, key) {
    var row = document.getElementById(rowId);
    if (!row) { return; }
    row.addEventListener('click', function (clickEvent) {
      var button = clickEvent.target.closest('.chip');
      if (!button) { return; }
      Array.prototype.forEach.call(row.querySelectorAll('.chip'), function (chip) {
        chip.classList.remove('active');
      });
      button.classList.add('active');
      state[key] = button.getAttribute('data-' + key);
      state.shown = PAGE_SIZE;
      render();
    });
  }

  function init() {
    cacheElements();
    fillSelect(el.province, provinceList(), 'All provinces');
    fillSelect(el.city, cityList('all'), 'All cities');

    bindChips('when-row', 'when');
    bindChips('cat-row', 'cat');

    el.q.addEventListener('input', function () {
      state.q = el.q.value.trim();
      state.shown = PAGE_SIZE;
      render();
    });
    el.province.addEventListener('change', function () {
      state.province = el.province.value;
      state.city = 'all';
      fillSelect(el.city, cityList(state.province), 'All cities');
      state.shown = PAGE_SIZE;
      render();
    });
    el.city.addEventListener('change', function () {
      state.city = el.city.value;
      state.shown = PAGE_SIZE;
      render();
    });
    el.day.addEventListener('change', function () {
      state.day = el.day.value;
      state.shown = PAGE_SIZE;
      render();
    });
    el.reset.addEventListener('click', function () {
      state = { q: '', when: 'all', cat: 'all', province: 'all', city: 'all', day: 'all', shown: PAGE_SIZE };
      el.q.value = '';
      el.day.value = 'all';
      fillSelect(el.province, provinceList(), 'All provinces');
      fillSelect(el.city, cityList('all'), 'All cities');
      Array.prototype.forEach.call(document.querySelectorAll('.chip'), function (chip) {
        chip.classList.toggle('active', chip.getAttribute('data-when') === 'all' || chip.getAttribute('data-cat') === 'all');
      });
      render();
    });

    if (el.aboutBtn && el.about) {
      el.aboutBtn.addEventListener('click', function () {
        if (typeof el.about.showModal === 'function') { el.about.showModal(); }
      });
    }

    var windowText = data.window
      ? formatRange(data.window.from, data.window.to) + ' - weekends only'
      : 'Weekends in the Netherlands';
    el.windowLabel.textContent = windowText;

    if (data.generated_at) {
      el.updated.textContent = 'Dataset updated ' + data.generated_at.replace('T', ' ').replace('Z', ' UTC')
        + ' - ' + (data.total || 0) + ' activities.';
    }

    fillSources(el.sources, data.sources || []);
    if (el.aboutSources) { fillSources(el.aboutSources, data.sources || []); }

    render();
  }

  if (typeof document === 'undefined') {
    /* Non-browser environment (unit tests): only expose the pure helpers. */
  } else if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', init);
  } else {
    init();
  }
}(typeof globalThis !== 'undefined' ? globalThis : this));